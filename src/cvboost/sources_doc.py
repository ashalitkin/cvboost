"""SOURCES.md: connector metadata (code) + docs/sources_meta.yaml (human facts).

`cvboost sources --markdown` prints the document. It touches no database and no .env: it only
imports the connector classes and reads the YAML file, so the owner's data can never leak into it.
"""

from __future__ import annotations

from datetime import timedelta
from pathlib import Path

import yaml

from cvboost import connectors

META_PATH = Path(__file__).resolve().parents[2] / "docs" / "sources_meta.yaml"
FIELDS = ("gives", "where", "price", "limits", "notes")
KIND_NAMES = {
    "api": "JSON API",
    "rss": "RSS feed",
    "ats": "company career pages (ATS)",
    "email": "job-alert e-mails",
    "html": "HTML page",
    "browser": "browser",
}


def load_meta(path: Path = META_PATH) -> dict[str, dict[str, str]]:
    data = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    return {str(k): {f: str(v.get(f) or "") for f in FIELDS} for k, v in data.items()}


def missing_meta(meta: dict[str, dict[str, str]]) -> list[str]:
    """Problems that make the document incomplete (empty list = complete)."""
    problems = [f"no entry for connector {n}" for n in connectors.REGISTRY if n not in meta]
    problems += [f"entry {n} has no connector" for n in meta if n not in connectors.REGISTRY]
    for n, m in meta.items():
        for f in ("gives", "price", "limits"):
            if not m.get(f, "").strip():
                problems.append(f"{n}: empty '{f}'")
        cls = connectors.REGISTRY.get(n)
        if cls is not None and getattr(cls, "env_vars", None) and not m.get("where", "").strip():
            problems.append(f"{n}: needs keys but 'where' is empty")
    return problems


def _every(delta: timedelta) -> str:
    s = delta.total_seconds()
    return f"{s / 3600:g} h" if s >= 3600 else f"{s / 60:g} min"


def _key(cls) -> str:
    env = getattr(cls, "env_vars", ())
    if env:
        return ", ".join(f"`{v}`" for v in env)
    if cls.name == "email_alerts":
        return "`CVBOOST_IMAP_USER`, `CVBOOST_IMAP_PASSWORD`"
    if cls.kind == "ats":
        return "company list"
    return "none"


def render_markdown(meta: dict[str, dict[str, str]] | None = None) -> str:
    meta = meta if meta is not None else load_meta()
    problems = missing_meta(meta)
    if problems:
        raise ValueError("docs/sources_meta.yaml is incomplete: " + "; ".join(problems))
    out = [
        "# Sources",
        "",
        "Generated by `cvboost sources --markdown` from the connector code and "
        "`docs/sources_meta.yaml`. Do not edit by hand.",
        "",
        "Every source is a small connector. They prefer official APIs and feeds, wait politely "
        "between requests and identify themselves with a generic User-Agent. LinkedIn, Indeed "
        "and Glassdoor pages are never scraped: use their job-alert e-mails (`email_alerts`).",
        "",
        "Most sources need nothing from you. Three need a free key, one needs a mailbox, and "
        "the company career pages need a list of companies in `config/companies.yaml`.",
        "",
        "| Source | Kind | Needs | Price | Default | Checks every |",
        "|---|---|---|---|---|---|",
    ]
    for name, cls in connectors.REGISTRY.items():
        out.append(
            f"| [{name}](#{name}) | {KIND_NAMES.get(cls.kind, cls.kind)} | {_key(cls)} | "
            f"{meta[name]['price'].split(';')[0].rstrip('.')} | "
            f"{'on' if cls.default_enabled else 'off'} | {_every(cls.interval)} |"
        )
    out.append("")
    for name, cls in connectors.REGISTRY.items():
        m = meta[name]
        out += [f"## {name}", "", m["gives"], ""]
        out.append(f"- **Kind:** {KIND_NAMES.get(cls.kind, cls.kind)}, `{cls.base_url}`")
        out.append(f"- **Key or setup needed:** {_key(cls)}")
        if m["where"]:
            out.append(f"- **Where to get it:** {m['where']}")
        out.append(f"- **Price:** {m['price']}")
        out.append(f"- **Limits:** {m['limits']}")
        out.append(
            f"- **Runs:** every {_every(cls.interval)}, "
            f"{'on' if cls.default_enabled else 'off'} by default"
        )
        out.append(f"- **Terms of service:** {cls.tos_note}")
        out.append(f"- **Attribution in the panel:** {cls.attribution}")
        if m["notes"]:
            out.append(f"- **Note:** {m['notes']}")
        out.append("")
    return "\n".join(out).rstrip() + "\n"
